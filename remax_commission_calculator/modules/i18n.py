def normalize_language(language):
    if language in SUPPORTED_LANGUAGES:
        return language

    return DEFAULT_LANGUAGE


def _translation_placeholders(text):
    from string import Formatter

    return [
        field_name
        for _, field_name, _, _ in Formatter().parse(text)
        if field_name is not None
    ]


def translate(key, language=DEFAULT_LANGUAGE, **kwargs):
    language = normalize_language(language)

    if key == "app_title":
        return get_brand_name()

    if key == "app_footer":
        return get_brand_footer(language)

    catalog = TRANSLATIONS.get(
        language,
        TRANSLATIONS[DEFAULT_LANGUAGE]
    )

    if key in catalog:
        text = catalog[key]
    else:
        fallback = TRANSLATIONS[DEFAULT_LANGUAGE]
        text = fallback.get(key, key)

    format_kwargs = dict(kwargs)

    if "{brand_name}" in text:
        format_kwargs.setdefault("brand_name", get_brand_name())

    if not format_kwargs:
        return text

    placeholders = _translation_placeholders(text)

    if placeholders and all(
        placeholder in format_kwargs
        for placeholder in placeholders
    ):
        return text.format(**format_kwargs)

    return text


def _translate_field_label(field_source, language):
    field_key = FIELD_SOURCE_TO_KEY.get(
        field_source
    )

    if field_key is None:
        return field_source

    return translate(field_key, language)


def localize_message(message, language=DEFAULT_LANGUAGE):
    if message is None:
        return ""

    message = str(message).strip()
    language = normalize_language(language)

    if message in TRANSLATIONS.get(language, {}):
        return translate(message, language)

    if message in TRANSLATIONS[DEFAULT_LANGUAGE]:
        return translate(message, language)

    compact = " ".join(message.split())

    if compact in EXACT_ERROR_TO_KEY:
        return translate(
            EXACT_ERROR_TO_KEY[compact],
            language
        )

    for pattern, error_key in ERROR_PATTERNS:
        match = re.match(pattern, compact)

        if match:
            field_label = _translate_field_label(
                match.group(1),
                language
            )
            return translate(
                error_key,
                language,
                field=field_label
            )

    return message


def localize_messages(messages, language=DEFAULT_LANGUAGE):
    return [
        localize_message(message, language)
        for message in messages
    ]
